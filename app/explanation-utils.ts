const FORMAL_ENDINGS: Array<[RegExp, string]> = [
  [/아니다\./gu, "아닙니다."],
  [/다르다\./gu, "다릅니다."],
  [/없다\./gu, "없습니다."],
  [/있다\./gu, "있습니다."],
  [/않는다\./gu, "않습니다."],
  [/않다\./gu, "않습니다."],
  [/일반적이다\./gu, "일반적입니다."],
  [/중요하다\./gu, "중요합니다."],
  [/동일하다\./gu, "동일합니다."],
  [/반영한다\./gu, "반영합니다."],
  [/구분한다\./gu, "구분합니다."],
  [/제외한다\./gu, "제외합니다."],
  [/조정한다\./gu, "조정합니다."],
  [/지급한다\./gu, "지급합니다."],
  [/평가한다\./gu, "평가합니다."],
  [/합산한다\./gu, "합산합니다."],
  [/가중평균한다\./gu, "가중평균합니다."],
  [/연결한다\./gu, "연결합니다."],
  [/고려된다\./gu, "고려됩니다."],
  [/달라진다\./gu, "달라집니다."],
  [/나타낸다\./gu, "나타냅니다."],
  [/나눈다\./gu, "나눕니다."],
  [/받는다\./gu, "받습니다."],
  [/준다\./gu, "줍니다."],
  [/된다\./gu, "됩니다."],
  [/한다\./gu, "합니다."],
  [/([가-힣]+)이다\./gu, "$1입니다."],
  [/(기호|이자|거래)다\./gu, "$1입니다."],
  [/([0-9%,.)]+)이다\./gu, "$1입니다."],
  [/([0-9%,.)]+)다\./gu, "$1입니다."],
];

/**
 * 원문 데이터의 사실과 숫자는 바꾸지 않고, 사용자에게 보이는 설명 종결어미만
 * 정중한 `~습니다/~입니다` 체로 통일합니다.
 */
export function formalizeExplanation(value: string) {
  return FORMAL_ENDINGS.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), value.trim());
}
